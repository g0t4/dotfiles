-- nvim --clean --headless '+luafile tests/nvim/completion_auto_select.lua'
vim.opt.rtp:prepend(vim.fn.getcwd() .. '/.config/nvim')
require('plugins.completions.nvim_native.keymaps').setup({ auto_select = true })
vim.o.completeopt = 'menuone,noselect,fuzzy'
local function keys(s) vim.api.nvim_feedkeys(vim.keycode(s), 'xt!', false) end
vim.keymap.set('i', '<F2>', function()
    vim.fn.complete(vim.api.nvim_win_get_cursor(0)[2] - 2, { 'hello', 'help' })
end)
vim.keymap.set('i', '<F3>', function()
    vim.fn.complete(vim.api.nvim_win_get_cursor(0)[2] + 1, { 'hello', 'help' })
end)
local function later(fn)
    vim.defer_fn(function()
        local ok, err = pcall(fn)
        if not ok then print(err); vim.cmd.cquit() end
    end, 50)
end
later(function()
    assert(vim.fn.complete_info().selected == 0, 'first result not selected')
    assert(vim.api.nvim_get_current_line() == 'hel', 'selection inserted text')
    vim.api.nvim_feedkeys(vim.keycode('<CR><Esc>'), 't', false)
    later(function()
        assert(vim.api.nvim_get_current_line() == 'hello', 'Return did not accept first result: ' .. vim.inspect(vim.api.nvim_get_current_line()))
        vim.cmd.undo()
        assert(vim.api.nvim_get_current_line() == 'hel', 'completion undo lost prefix')
        vim.cmd.enew({ bang = true })
        vim.api.nvim_feedkeys(vim.keycode('i <F3>'), 't', false)
        later(function()
            assert(vim.fn.complete_info().selected == -1, 'selected result after whitespace')
            vim.api.nvim_feedkeys(vim.keycode('<CR><Esc>'), 't', false)
            later(function()
                assert(vim.deep_equal(vim.api.nvim_buf_get_lines(0, 0, -1, false), { ' ', '' }), 'whitespace Return accepted completion')
                print('PASS first-result selection, no insertion, acceptance, undo, whitespace newline')
                vim.cmd.qa({ bang = true })
            end)
        end)
    end)
end)
keys('ihel<F2>')
